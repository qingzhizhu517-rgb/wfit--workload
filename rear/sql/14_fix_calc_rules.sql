-- ============================================================================
-- 14_fix_calc_rules.sql  核算规则值修正（幂等，可重复执行）
--
-- 背景：02/11 种子脚本用 INSERT IGNORE，已部署库中的旧值不会被覆盖，
--       故对需要变更的规则值用显式 UPDATE 修正。
--
-- 变更：G4 课程设计指导人数上限 CAP_R4_MAX 20 → 60
--       （权威来源 else/工作量.md：R4≤60；原种子/代码默认 20 会把 20~60 人少算）
-- ============================================================================

UPDATE biz_workload_rule
SET rule_value = 60.00
WHERE rule_code = 'CAP_R4_MAX' AND rule_value <> 60.00;
